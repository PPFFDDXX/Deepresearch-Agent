"""Provider-independent structured report schema; sources are application-owned."""

from collections.abc import Iterator
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator


class ReportRecord(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, str_strip_whitespace=True)


class CitedParagraph(ReportRecord):
    text: str = Field(min_length=1, max_length=3000)
    evidence_ids: list[str] = Field(min_length=1, max_length=10)

    @field_validator("evidence_ids")
    @classmethod
    def unique_evidence_ids(cls, value: list[str]) -> list[str]:
        if len(set(value)) != len(value) or any(not item.strip() for item in value):
            raise ValueError("Evidence IDs must be nonempty and unique within a paragraph")
        return value


class AnalysisSection(ReportRecord):
    title: str = Field(min_length=1, max_length=160)
    paragraphs: list[CitedParagraph] = Field(min_length=1, max_length=6)


class ReportDraft(ReportRecord):
    executive_summary: list[CitedParagraph] = Field(min_length=1, max_length=4)
    key_findings: list[CitedParagraph] = Field(min_length=1, max_length=10)
    detailed_analysis: list[AnalysisSection] = Field(min_length=1, max_length=8)
    conclusion: list[CitedParagraph] = Field(min_length=1, max_length=4)


class ReportCitation(ReportRecord):
    """Display reference copied from an existing Citation, never generated by LLM."""

    number: int = Field(ge=1)
    citation_id: str = Field(min_length=1)
    title: str = Field(min_length=1)
    source_type: Literal["web", "local"]
    locator: str = Field(min_length=1)
    locations: list[str]


def iter_paragraphs(report: ReportDraft) -> Iterator[CitedParagraph]:
    """Traverse in report reading order, used for validation and source numbering."""
    yield from report.executive_summary
    yield from report.key_findings
    for section in report.detailed_analysis:
        yield from section.paragraphs
    yield from report.conclusion
